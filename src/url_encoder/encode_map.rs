use std::collections::HashMap;
use std::sync::LazyLock;

pub static URL_ENCODE_SYMBOLS: LazyLock<HashMap<char, &'static str>> = LazyLock::new(|| {
    [
        (' ', "+"),
        ('#', "%23"),
        ('$', "%24"),
        ('%', "%25"),
        ('&', "%26"),
        ('\'', "%27"),
        ('(', "%28"),
        (')', "%29"),
        ('*', "%2A"),
        ('+', "%2B"),
        (',', "%2C"),
        ('/', "%2F"),
        (':', "%3A"),
        (';', "%3B"),
        ('=', "%3D"),
        ('?', "%3F"),
        ('@', "%40"),
        ('[', "%5B"),
        (']', "%5D"),
        ('|', "%7C"),
        ('"', "%22"),
        ('<', "%3C"),
        ('>', "%3E"),
        ('\\', "%5C"),
        ('^', "%5E"),
        ('`', "%60"),
        ('{', "%7B"),
        ('}', "%7D"),
        ('\t', "%09"),
        ('\r', "%0D"),
        ('\n', "%0A"),
    ]
    .iter()
    .copied()
    .collect()
});
